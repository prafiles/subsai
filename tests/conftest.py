#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
Shared pytest fixtures.

`_pywhispercpp` is a pybind11 native extension built from the pywhispercpp
sdist; the sdist ships the `whisper.cpp`/`pybind11` git submodules empty, so
the extension cannot be compiled in this environment. `subsai.configs` imports
`WhisperCppModel` eagerly, which imports `pywhispercpp.model`, which imports
`_pywhispercpp`. To keep `import subsai` working without the native library,
register a minimal stub exposing only the constants touched at import time.
The stub is installed only when the real extension is unavailable, so
environments with a real build are unaffected. All pywhispercpp *logic* used
by subsai (Model construction, transcribe) is patched per-test anyway.
"""
import importlib.util
import shutil
import subprocess
import sys
import types

import pysubs2
import pytest

if importlib.util.find_spec("_pywhispercpp") is None:
    _stub = types.ModuleType("_pywhispercpp")
    _stub.WHISPER_SAMPLING_GREEDY = 0
    _stub.WHISPER_SAMPLING_BEAM_SEARCH = 1
    _stub.WHISPER_SAMPLE_RATE = 16000

    class _SamplingStrategy:
        WHISPER_SAMPLING_GREEDY = 0
        WHISPER_SAMPLING_BEAM_SEARCH = 1

    _stub.whisper_sampling_strategy = _SamplingStrategy
    _stub.whisper_full_default_params = lambda strategy: None
    sys.modules["_pywhispercpp"] = _stub


def _require_ffmpeg():
    if shutil.which("ffmpeg") is None:
        pytest.skip("ffmpeg binary not available")


@pytest.fixture(scope="session")
def tiny_wav(tmp_path_factory):
    """2 s 440 Hz sine WAV generated by ffmpeg (no speech, tiny)."""
    _require_ffmpeg()
    out = tmp_path_factory.mktemp("media") / "tiny.wav"
    subprocess.run(
        ["ffmpeg", "-y", "-f", "lavfi", "-i", "sine=frequency=440:duration=2",
         str(out)],
        check=True, capture_output=True,
    )
    return str(out)


@pytest.fixture(scope="session")
def tiny_mp4(tmp_path_factory):
    """2 s video+audio MP4 generated by ffmpeg, for merge_subs_with_video."""
    _require_ffmpeg()
    out = tmp_path_factory.mktemp("media") / "tiny.mp4"
    subprocess.run(
        ["ffmpeg", "-y",
         "-f", "lavfi", "-i", "testsrc=size=128x96:rate=10:duration=2",
         "-f", "lavfi", "-i", "sine=frequency=440:duration=2",
         "-c:v", "libx264", "-c:a", "aac", "-shortest", str(out)],
        check=True, capture_output=True,
    )
    return str(out)


@pytest.fixture
def sample_subs():
    """A small in-memory SSAFile with two events."""
    subs = pysubs2.SSAFile()
    e1 = pysubs2.SSAEvent(start=pysubs2.make_time(s=1), end=pysubs2.make_time(s=3))
    e1.text = "Hello world"
    e2 = pysubs2.SSAEvent(start=pysubs2.make_time(s=4), end=pysubs2.make_time(s=6))
    e2.text = "Second line"
    subs.append(e1)
    subs.append(e2)
    return subs
